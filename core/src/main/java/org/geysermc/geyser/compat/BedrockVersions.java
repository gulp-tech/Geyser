package org.geysermc.geyser.compat;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import org.checkerframework.checker.nullness.qual.NonNull;
import org.checkerframework.checker.nullness.qual.Nullable;
import org.geysermc.geyser.GeyserImpl;
import org.geysermc.geyser.util.JsonUtils;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * The Bedrock protocol version table: every Minecraft: Bedrock Edition version that the protocol
 * library knows about, mapped to its protocol version.
 *
 * <p>Generated by {@code tools/compat-gen/fetch_bedrock_versions.py} from the codec classes of
 * CloudburstMC/Protocol, so it always matches the library that Geyser is compiled against.</p>
 *
 * <p>Having the table in code lets compat data be authored in human terms
 * ({@code "since": "1.21.50"}) instead of protocol numbers, and lets the login path and messages
 * talk about versions rather than magic integers.</p>
 */
public final class BedrockVersions {

    private static final String RESOURCE = "compat/bedrock-versions.json";

    private static volatile BedrockVersions instance;

    private final Map<String, Integer> byVersion;
    private final Map<Integer, String> byProtocol;
    private final List<Integer> protocols;

    private BedrockVersions(@NonNull Map<String, Integer> byVersion, @NonNull Map<Integer, String> byProtocol) {
        this.byVersion = byVersion;
        this.byProtocol = byProtocol;

        List<Integer> protocols = new ArrayList<>(byProtocol.keySet());
        Collections.sort(protocols);
        this.protocols = Collections.unmodifiableList(protocols);
    }

    /**
     * @return the shared table, loaded on first use
     */
    public static @NonNull BedrockVersions get() {
        BedrockVersions current = instance;
        if (current != null) {
            return current;
        }
        synchronized (BedrockVersions.class) {
            if (instance == null) {
                instance = load();
            }
            return instance;
        }
    }

    /**
     * Resolves a version name to its protocol version.
     *
     * <p>Both spellings are accepted, because Geyser drops the leading {@code 1.} for the 1.26
     * series ({@code 26.60}) while the protocol library keeps it ({@code 1.26.60}).</p>
     *
     * @param version the Minecraft: Bedrock Edition version, e.g. {@code 1.21.50} or {@code 26.60}
     * @return the protocol version, or {@code -1} if the version is unknown
     */
    public int protocolOf(@Nullable String version) {
        if (version == null || version.isEmpty()) {
            return -1;
        }
        String normalized = version.trim().toLowerCase(Locale.ROOT);

        Integer protocol = byVersion.get(normalized);
        if (protocol != null) {
            return protocol;
        }
        // "26.60" <-> "1.26.60"
        if (normalized.startsWith("1.")) {
            protocol = byVersion.get(normalized.substring(2));
        } else {
            protocol = byVersion.get("1." + normalized);
        }
        return protocol == null ? -1 : protocol;
    }

    /**
     * @param protocol the protocol version
     * @return the Minecraft version name, or {@code null} if unknown
     */
    public @Nullable String versionOf(int protocol) {
        return byProtocol.get(protocol);
    }

    /**
     * @return every known protocol version, ascending
     */
    public @NonNull List<Integer> protocols() {
        return protocols;
    }

    /**
     * @param protocol the protocol version
     * @return the closest known protocol version at or below the given one, or {@code -1}
     */
    public int floorProtocol(int protocol) {
        int result = -1;
        for (int known : protocols) {
            if (known > protocol) {
                break;
            }
            result = known;
        }
        return result;
    }

    private static @NonNull BedrockVersions load() {
        Map<String, Integer> byVersion = new HashMap<>();
        Map<Integer, String> byProtocol = new HashMap<>();

        try (InputStream stream = BedrockVersions.class.getClassLoader().getResourceAsStream(RESOURCE)) {
            if (stream == null) {
                return empty();
            }
            JsonObject root = JsonUtils.parseJson(new String(stream.readAllBytes(), StandardCharsets.UTF_8));
            JsonElement versionsElement = root.get("versions");
            if (versionsElement == null || !versionsElement.isJsonArray()) {
                return empty();
            }

            JsonArray versions = versionsElement.getAsJsonArray();
            for (JsonElement element : versions) {
                if (!element.isJsonObject()) {
                    continue;
                }
                JsonObject entry = element.getAsJsonObject();
                JsonElement protocolElement = entry.get("protocol");
                JsonElement versionElement = entry.get("version");
                if (protocolElement == null || versionElement == null) {
                    continue;
                }
                try {
                    int protocol = protocolElement.getAsInt();
                    String version = versionElement.getAsString();
                    byVersion.put(version.toLowerCase(Locale.ROOT), protocol);
                    byProtocol.put(protocol, version);
                } catch (RuntimeException ignored) {
                    // Skip malformed entries, keep the rest of the table usable
                }
            }
        } catch (Throwable throwable) {
            GeyserImpl geyser = GeyserImpl.getInstance();
            if (geyser != null && geyser.getLogger() != null) {
                geyser.getLogger().warning("Compat: could not read " + RESOURCE + ": " + throwable);
            }
            return empty();
        }

        return new BedrockVersions(Collections.unmodifiableMap(byVersion), Collections.unmodifiableMap(byProtocol));
    }

    private static @NonNull BedrockVersions empty() {
        return new BedrockVersions(Map.of(), Map.of());
    }
}
